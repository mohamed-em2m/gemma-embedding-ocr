"""Benchmark GLM-OCR against EmbeddingOCR on the held-out OOD dataset.

The dataset is generated by ``scripts/build_ood_dataset.py``.  Prototype fonts
and evaluation fonts are disjoint, evaluation words are not added to the
EmbeddingOCR lexicon, and both systems receive the exact same image crops.
"""

from __future__ import annotations

import argparse
import gc
import json
import time
import traceback
from collections import defaultdict
from collections.abc import Sequence
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Protocol

import numpy as np
import torch
from PIL import Image

from embedding_ocr.data.glyph_renderer import ALL_CHAR_CLASSES, ARABIC_CLASSES
from embedding_ocr.data.ood_dataset import OODSample, load_ood_dataset
from embedding_ocr.eval.metrics import evaluate
from embedding_ocr.recognition.base import RecognitionEngine

EMBEDDING_ENGINES = ("gemma-char", "gemma-hier", "gemma-hybrid")
ALL_ENGINES = ("glm", *EMBEDDING_ENGINES)
DEFAULT_ENGINES = ("glm", "gemma-hybrid")
SINGLE_WORD_CATEGORIES = frozenset({"word", "diacritics", "ligature"})


class Predictor(Protocol):
    """Common evaluation interface."""

    name: str

    def predict(self, sample: OODSample, image: np.ndarray) -> tuple[str, float]:
        """Return recognized text and confidence for one crop."""
        ...


@dataclass
class EngineReport:
    name: str
    status: str = "ok"
    error: str = ""
    metrics: dict[str, Any] = field(default_factory=dict)
    groups: dict[str, dict[str, Any]] = field(default_factory=dict)
    latency_ms_mean: float = 0.0
    samples: list[dict[str, Any]] = field(default_factory=list)


class EnginePredictor:
    def __init__(self, name: str, engine: RecognitionEngine) -> None:
        self.name = name
        self.engine = engine

    def predict(self, sample: OODSample, image: np.ndarray) -> tuple[str, float]:
        del sample
        result = self.engine.recognize(image)
        return result.text, float(result.confidence)


class HybridEmbeddingPredictor:
    """Dispatch glyphs to character matching and words to hierarchical OCR."""

    def __init__(
        self,
        name: str,
        mode: str,
        char_engines: dict[str, RecognitionEngine],
        hier_engines: dict[str, RecognitionEngine],
    ) -> None:
        self.name = name
        self.mode = mode
        self.char_engines = char_engines
        self.hier_engines = hier_engines

    def predict(self, sample: OODSample, image: np.ndarray) -> tuple[str, float]:
        if self.mode == "char":
            engine = self.char_engines[sample.script]
        elif self.mode == "hier":
            engine = self.hier_engines[sample.script]
        else:
            engine = (
                self.char_engines[sample.script]
                if sample.category == "glyph"
                else self.hier_engines[sample.script]
            )

        # These categories are already cropped to one word/unit. Calling the
        # word-crop path directly avoids re-segmenting them and inserting
        # artificial spaces.
        if sample.category in SINGLE_WORD_CATEGORIES:
            word_recognizer = getattr(engine, "recognize_word_crop", None)
            if word_recognizer is not None:
                result = word_recognizer(image, depth=0)
                return result.text, float(result.confidence)

        result = engine.recognize(image)
        return result.text, float(result.confidence)


def _build_char_engine(
    embedder: Any, script: str, index_fonts: Sequence[str]
) -> RecognitionEngine:
    from embedding_ocr.recognition.embedding.engine import EmbeddingRecognizer
    from embedding_ocr.recognition.embedding.index import FaissIndex
    from embedding_ocr.recognition.embedding.prototypes import PrototypeDB

    classes = ALL_CHAR_CLASSES if script == "latin" else ARABIC_CLASSES
    prototype_db = PrototypeDB(
        embedder=embedder,
        index=FaissIndex(dim=embedder.dim),
        classes=classes,
        script=script,
    )
    prototype_db.build_from_fonts(list(index_fonts))
    return EmbeddingRecognizer(prototype_db=prototype_db, script=script)


def _build_hier_engine(
    embedder: Any,
    script: str,
    index_fonts: Sequence[str],
    char_engine: RecognitionEngine,
    max_words: int | None = None,
    max_subwords: int | None = None,
    use_visual_prototypes: bool = False,
) -> RecognitionEngine:
    from embedding_ocr.recognition.embedding.hierarchical.alignment import (
        EmbeddingAlignmentSegmenter,
        VocabularyPrototypeDB,
    )
    from embedding_ocr.recognition.embedding.hierarchical.engine import (
        HierarchicalWordRecognizer,
    )
    from embedding_ocr.recognition.embedding.hierarchical.vocabulary import (
        EmbeddingVocabulary,
    )

    vocabulary = EmbeddingVocabulary(
        embedder=embedder,
        cache_dir=Path("artifacts") / f"ood_vocab_{script}",
        prototype_fonts=list(index_fonts),
        use_visual_prototypes=use_visual_prototypes,
        script=script,
    )
    # Use the full tokenizer vocabulary by default. Token IDs are not
    # frequency-ordered, so a small cap silently removes rare words such as
    # the held-out OOD lexicon.
    vocabulary.extract_and_organize_tokens(
        max_words=max_words,
        max_subwords=max_subwords,
    )
    vocabulary.build_indexes()

    aligner = None
    if script == "arabic":
        prototype_db = getattr(char_engine, "prototype_db", None)
        aligner = EmbeddingAlignmentSegmenter(
            prototype_db=(
                prototype_db
                if prototype_db is not None
                else VocabularyPrototypeDB(embedder, vocabulary)
            ),
            top_k=5,
            min_similarity=0.35,
            strategy="pruned",
        )

    return HierarchicalWordRecognizer(
        embedder=embedder,
        vocabulary=vocabulary,
        script=script,
        unit_aligner=aligner,
        use_alignment=script == "arabic",
        min_word_sim=0.74,
        min_word_margin=0.005,
        min_subword_sim=0.71,
        min_subword_margin=0.003,
        min_char_sim=0.62,
    )


def _group_metrics(
    samples: Sequence[OODSample],
    predictions: Sequence[str],
) -> dict[str, dict[str, Any]]:
    buckets: dict[str, list[tuple[OODSample, str]]] = defaultdict(list)
    for sample, prediction in zip(samples, predictions, strict=False):
        buckets[f"script:{sample.script}"].append((sample, prediction))
        buckets[f"category:{sample.script}/{sample.category}"].append(
            (sample, prediction)
        )
        buckets[f"condition:{sample.condition}"].append((sample, prediction))

    groups: dict[str, dict[str, Any]] = {}
    for name, rows in buckets.items():
        references = [sample.text for sample, _ in rows]
        hypotheses = [prediction for _, prediction in rows]
        metrics = evaluate(references, hypotheses, normalize=True)
        metrics["raw_cer"] = evaluate(references, hypotheses, normalize=False)["cer"]
        metrics["raw_exact_match"] = evaluate(references, hypotheses, normalize=False)[
            "exact_match"
        ]
        groups[name] = metrics
    return groups


def evaluate_predictor(
    predictor: Predictor,
    samples: Sequence[OODSample],
) -> EngineReport:
    report = EngineReport(name=predictor.name)
    references: list[str] = []
    hypotheses: list[str] = []
    latencies: list[float] = []
    rows: list[dict[str, Any]] = []

    try:
        for index, sample in enumerate(samples, start=1):
            image = np.asarray(
                Image.open(sample.image_path).convert("RGB"), dtype=np.uint8
            )
            started = time.perf_counter()
            prediction, confidence = predictor.predict(sample, image)
            latency_ms = (time.perf_counter() - started) * 1000.0
            references.append(sample.text)
            hypotheses.append(prediction)
            latencies.append(latency_ms)
            rows.append(
                {
                    "id": sample.sample_id,
                    "text": sample.text,
                    "prediction": prediction,
                    "confidence": confidence,
                    "script": sample.script,
                    "category": sample.category,
                    "condition": sample.condition,
                    "font": sample.font,
                    "latency_ms": latency_ms,
                }
            )
            if index % 25 == 0 or index == len(samples):
                print(f"  [{index}/{len(samples)}] {sample.text!r} -> {prediction!r}")
    except Exception as exc:  # pragma: no cover - depends on optional engines
        report.status = "unavailable"
        report.error = f"{type(exc).__name__}: {exc}"
        traceback.print_exc()
        return report

    report.metrics = evaluate(references, hypotheses, normalize=True)
    report.metrics["raw_cer"] = evaluate(references, hypotheses, normalize=False)["cer"]
    report.metrics["raw_exact_match"] = evaluate(
        references, hypotheses, normalize=False
    )["exact_match"]
    report.latency_ms_mean = float(np.mean(latencies)) if latencies else 0.0
    report.groups = _group_metrics(samples, hypotheses)
    report.samples = rows
    return report


def _release_memory() -> None:
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def _load_samples(manifest: Path, limit_per_script: int | None) -> list[OODSample]:
    samples = load_ood_dataset(manifest)
    if limit_per_script is None:
        return samples

    selected: list[OODSample] = []
    for script in ("latin", "arabic"):
        script_samples = [sample for sample in samples if sample.script == script]
        if not script_samples:
            continue
        groups: dict[tuple[str, str], list[OODSample]] = defaultdict(list)
        for sample in script_samples:
            groups[(sample.category, sample.condition)].append(sample)

        # Round-robin over condition/category groups so a small limit still
        # covers both clean and degraded crops and multiple categories.
        ordered_groups = [
            groups[key] for key in sorted(groups, key=lambda key: (key[1], key[0]))
        ]
        script_selected: list[OODSample] = []
        for round_index in range(
            max((len(group) for group in ordered_groups), default=0)
        ):
            for group in ordered_groups:
                if round_index >= len(group):
                    continue
                script_selected.append(group[round_index])
                if len(script_selected) >= limit_per_script:
                    break
            if len(script_selected) >= limit_per_script:
                break
        selected.extend(script_selected)
    return selected


def _ensure_dataset(manifest: Path, auto_build: bool) -> None:
    """Create the manifest when it is missing (for fresh Kaggle/Colab runs)."""
    if manifest.exists() and (manifest.parent / "dataset.json").exists():
        return
    if not auto_build:
        msg = (
            f"manifest not found: {manifest}. Run "
            "`python scripts/build_ood_dataset.py` first, or omit "
            "`--no-build-dataset`."
        )
        raise FileNotFoundError(msg)

    from embedding_ocr.data.ood_dataset import build_ood_dataset

    print(f"Dataset not found at {manifest.parent}; building it now...")
    try:
        build_ood_dataset(manifest.parent, overwrite=manifest.exists())
    except Exception as exc:
        msg = (
            "could not build the OOD dataset. Check that the fonts listed in "
            "`src/embedding_ocr/data/ood_dataset.py` are installed, or run "
            f"`python scripts/build_ood_dataset.py --out {manifest.parent}` manually."
        )
        raise RuntimeError(msg) from exc


def _write_markdown(report: dict[str, Any], path: Path) -> None:
    lines = [
        "# Out-of-Distribution OCR Benchmark: Latin + Arabic",
        "",
        f"> **Manifest:** `{report['manifest']}`  ",
        f"> **Samples:** {report['num_samples']}  ",
        "> **Prototype fonts:** disjoint from evaluation fonts  ",
        "> **EmbeddingOCR lexicon:** no evaluation words added",
        "",
        "## Overall",
        "",
        "| Engine | Status | CER | WER | Exact | Latency |",
        "| :--- | :---: | ---: | ---: | ---: | ---: |",
    ]
    for engine in report["engines"]:
        if engine["status"] != "ok":
            lines.append(f"| {engine['name']} | *unavailable* | - | - | - | - |")
            continue
        metrics = engine["metrics"]
        lines.append(
            f"| {engine['name']} | **ok** | {metrics['cer'] * 100:.2f}% | "
            f"{metrics['wer'] * 100:.2f}% | {metrics['exact_match'] * 100:.1f}% | "
            f"{engine['latency_ms_mean']:.1f} ms |"
        )

    lines.extend(["", "## Breakdown", ""])
    lines.append("| Engine | Group | N | CER | WER | Exact |")
    lines.append("| :--- | :--- | ---: | ---: | ---: | ---: |")
    for engine in report["engines"]:
        if engine["status"] != "ok":
            continue
        for group_name in sorted(engine["groups"]):
            metrics = engine["groups"][group_name]
            lines.append(
                f"| {engine['name']} | {group_name} | "
                f"{int(metrics['num_samples'])} | {metrics['cer'] * 100:.2f}% | "
                f"{metrics['wer'] * 100:.2f}% | "
                f"{metrics['exact_match'] * 100:.1f}% |"
            )

    unavailable = [engine for engine in report["engines"] if engine["status"] != "ok"]
    if unavailable:
        lines.extend(["", "## Unavailable Engines", ""])
        for engine in unavailable:
            lines.append(f"- **{engine['name']}**: `{engine['error']}`")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default="data/ood_latin_arabic_v1/manifest.jsonl")
    parser.add_argument("--output", default="docs/ood_ocr_benchmark.json")
    parser.add_argument(
        "--engines",
        nargs="+",
        default=list(DEFAULT_ENGINES),
        choices=list(ALL_ENGINES),
    )
    parser.add_argument("--device", default="auto")
    parser.add_argument("--gemma-dim", type=int, default=768)
    parser.add_argument(
        "--hier-max-words",
        type=int,
        default=None,
        help="Cap hierarchical word candidates (default: full tokenizer vocabulary).",
    )
    parser.add_argument(
        "--hier-max-subwords",
        type=int,
        default=None,
        help="Cap hierarchical subword candidates (default: full tokenizer vocabulary).",
    )
    parser.add_argument(
        "--hier-visual-prototypes",
        action="store_true",
        help="Use rendered font prototypes for hierarchical words/subwords.",
    )
    parser.add_argument(
        "--limit-per-script",
        type=int,
        default=None,
        help=(
            "Evaluate at most N samples per script, stratified across "
            "categories and conditions (useful for smoke tests)."
        ),
    )
    parser.add_argument("--skip-glm", action="store_true")
    parser.add_argument(
        "--no-build-dataset",
        action="store_true",
        help="Fail instead of generating the OOD dataset when the manifest is missing.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    manifest = Path(args.manifest)
    _ensure_dataset(manifest, auto_build=not args.no_build_dataset)

    samples = _load_samples(manifest, args.limit_per_script)
    print(f"Loaded {len(samples)} OOD samples from {manifest}")
    selected = [name for name in args.engines if name != "glm"]
    if not args.skip_glm and "glm" in args.engines:
        selected = ["glm", *selected]

    reports: list[EngineReport] = []

    if "glm" in selected:
        print("\n=== GLM-OCR ===")
        try:
            from embedding_ocr.recognition.glm_ocr import GLMOCRRecognizer

            glm = GLMOCRRecognizer(model_id="zai-org/GLM-OCR", device=args.device)
            reports.append(evaluate_predictor(EnginePredictor("GLM-OCR", glm), samples))
            del glm
        except Exception as exc:
            reports.append(
                EngineReport(
                    name="GLM-OCR",
                    status="unavailable",
                    error=f"{type(exc).__name__}: {exc}",
                )
            )
            traceback.print_exc()
        _release_memory()

    embedding_selected = [name for name in selected if name in EMBEDDING_ENGINES]
    if embedding_selected:
        from embedding_ocr.recognition.embedding.embedder import EmbeddingGemma2

        print("\nLoading EmbeddingGemma 2...")
        embedder = EmbeddingGemma2(
            dim=args.gemma_dim,
            device=args.device,
            batch_size=8,
        )

        index_fonts: dict[str, list[str]] = {}
        dataset_meta = json.loads((manifest.parent / "dataset.json").read_text())
        for script in ("latin", "arabic"):
            fonts = [
                font
                for font in dataset_meta["index_fonts"].get(script, [])
                if Path(font).exists()
            ]
            if not fonts:
                msg = f"no prototype fonts available for {script!r}"
                raise ValueError(msg)
            index_fonts[script] = fonts

        print("Building character prototype engines...")
        char_engines = {
            script: _build_char_engine(embedder, script, fonts)
            for script, fonts in index_fonts.items()
        }
        hier_max_words = args.hier_max_words
        hier_max_subwords = args.hier_max_subwords
        if args.hier_visual_prototypes:
            # Visual prototypes multiply each candidate by the number of fonts;
            # keep explicit safe caps unless the user overrides them.
            hier_max_words = hier_max_words or 4000
            hier_max_subwords = hier_max_subwords or 3000

        print("Building hierarchical engines...")
        hier_engines = {
            script: _build_hier_engine(
                embedder,
                script,
                fonts,
                char_engines[script],
                max_words=hier_max_words,
                max_subwords=hier_max_subwords,
                use_visual_prototypes=args.hier_visual_prototypes,
            )
            for script, fonts in index_fonts.items()
        }

        modes = {
            "gemma-char": "char",
            "gemma-hier": "hier",
            "gemma-hybrid": "hybrid",
        }
        for engine_name in embedding_selected:
            print(f"\n=== {engine_name} ===")
            predictor = HybridEmbeddingPredictor(
                name=engine_name,
                mode=modes[engine_name],
                char_engines=char_engines,
                hier_engines=hier_engines,
            )
            reports.append(evaluate_predictor(predictor, samples))
            _release_memory()

    output = Path(args.output)
    payload = {
        "manifest": str(manifest),
        "num_samples": len(samples),
        "hierarchical": {
            "max_words": args.hier_max_words,
            "max_subwords": args.hier_max_subwords,
            "visual_prototypes": args.hier_visual_prototypes,
        },
        "engines": [asdict(report) for report in reports],
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    markdown = output.with_suffix(".md")
    _write_markdown(payload, markdown)
    print(f"\nSaved results:\n  - {output}\n  - {markdown}")


if __name__ == "__main__":
    main()
